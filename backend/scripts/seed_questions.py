"""Cleanup + balanced generation of the quiz question bank. DEV ONLY — refuses
to run unless the target DB name ends in "dev".

Replaces the existing question bank with a balanced 100-question set:
  5 sets (a/b/c/d/None) x 5 topics x 4 questions = 100
  - per set: 20      - per topic: 20      - per (set,topic): 4
  - difficulty rotates the 4th slot per cell -> easy 34 / medium 33 / hard 33

Questions are generated by programmatic templates with COMPUTED correct answers
and computed distractors (modelling common errors), so the bank is internally
correct and evenly balanced across every variable — any imbalance observed in
downstream testing is then a real signal, not a fixture artifact.

Usage (from backend/ with the repo venv):
    python -m scripts.seed_questions            # wipe + regenerate (default)
    python -m scripts.seed_questions --dry-run  # print the distribution only
    python -m scripts.seed_questions --seed 7   # reproducible variant
"""
